export const adaptUser = {
  balanceUpdate: (message) => ({
    asset: message.a,
    balanceDelta: message.d,
    clearTime: message.T,
    eventTime: message.E,
    eventType: "balanceUpdate",
  }),
  outboundAccountInfo: (message) => ({
    eventType: "account",
    eventTime: message.E,
    makerCommissionRate: message.m,
    takerCommissionRate: message.t,
    buyerCommissionRate: message.b,
    sellerCommissionRate: message.s,
    canTrade: message.T,
    canWithdraw: message.W,
    canDeposit: message.D,
    lastAccountUpdate: message.u,
    balances: message.B.reduce((out, item) => {
      out[item.a] = { available: item.f, locked: item.l }
      return out
    }, {}),
  }),
  outboundAccountPosition: (message) => ({
    balances: message.B.map(({ a, f, l }) => ({ asset: a, free: f, locked: l })),
    eventTime: message.E,
    eventType: "outboundAccountPosition",
    lastAccountUpdate: message.u,
  }),
  executionReport: (message) => ({
    eventType: "executionReport",
    eventTime: message.E,
    symbol: message.s,
    newClientOrderId: message.c,
    originalClientOrderId: message.C,
    side: message.S,
    orderType: message.o,
    timeInForce: message.f,
    quantity: message.q,
    price: message.p,
    executionType: message.x,
    stopPrice: message.P,
    trailingDelta: message.d,
    icebergQuantity: message.F,
    orderStatus: message.X,
    orderRejectReason: message.r,
    orderId: message.i,
    orderTime: message.T,
    lastTradeQuantity: message.l,
    totalTradeQuantity: message.z,
    priceLastTrade: message.L,
    commission: message.n,
    commissionAsset: message.N,
    tradeId: message.t,
    isOrderWorking: message.w,
    isMaker: message.m,
    creationTime: message.O,
    totalQuoteTradeQuantity: message.Z,
    orderListId: message.g,
    quoteOrderQuantity: message.Q,
    lastQuoteTransacted: message.Y,
    trailingTime: message.D,
  }),
  listStatus: (message) => ({
    eventType: "listStatus",
    eventTime: message.E,
    symbol: message.s,
    orderListId: message.g,
    contingencyType: message.c,
    listStatusType: message.l,
    listOrderStatus: message.L,
    listRejectReason: message.r,
    listClientOrderId: message.C,
    transactionTime: message.T,
    orders: message.O.map((order) => ({
      symbol: order.s,
      orderId: order.i,
      clientOrderId: order.c,
    })),
  }),
}
